// Counts, per frontend locale, the messages with a translation, and writes the counts to
// frontend/src/locales/completeness.ts for the language picker and the system-language choice. A regional locale counts
// its own translation or its base language's, since it falls back to it. A test fails while the committed file is
// behind the catalogs; `bun run --cwd frontend i18n:compile` rewrites it.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const LOCALES = resolve(import.meta.dir, '../frontend/src/locales')
const OUT = join(LOCALES, 'completeness.ts')
const SOURCE_LOCALE = 'en'

export interface Count {
  translated: number
  total: number
}

function unquote(lines: string): string {
  return [...lines.matchAll(/^"(.*)"$/gm)].map((m) => JSON.parse(`"${m[1]}"`)).join('')
}

// msgid to translation ("" while untranslated or fuzzy), across a locale's catalogs; obsolete entries and headers are
// left out.
function translations(locale: string): Map<string, string> {
  const out = new Map<string, string>()
  const dir = join(LOCALES, locale)
  for (const file of readdirSync(dir).filter((f) => f.endsWith('.po'))) {
    for (const block of readFileSync(join(dir, file), 'utf8').split('\n\n')) {
      const match = /^msgid ((?:".*"\n)*?".*")\nmsgstr ((?:".*"\n?)+)/m.exec(
        block
          .split('\n')
          .filter((l) => !l.startsWith('#~'))
          .join('\n'),
      )
      const id = match?.[1] ? unquote(match[1]) : ''
      if (id === '' || !match?.[2]) {
        continue
      }
      const fuzzy = /^#,.*fuzzy/m.test(block)
      const str = fuzzy ? '' : unquote(match[2])
      out.set(id, str === '' ? (out.get(id) ?? '') : str)
    }
  }
  return out
}

export function count(
  locales: readonly string[],
  fallbacks: Record<string, string | undefined>,
): Record<string, Count> {
  const own = Object.fromEntries(locales.map((l) => [l, translations(l)]))
  return Object.fromEntries(
    locales.map((locale) => {
      const mine = own[locale]
      const base = own[fallbacks[locale] ?? ''] ?? new Map<string, string>()
      const total = mine?.size ?? 0
      const translated =
        locale === SOURCE_LOCALE
          ? total
          : [...(mine ?? [])].filter(([id, str]) => str !== '' || (base.get(id) ?? '') !== '')
              .length
      return [locale, { translated, total }]
    }),
  )
}

export function render(counts: Record<string, Count>): string {
  const rows = Object.entries(counts)
    .map(([locale, c]) => {
      const key = /^[a-z]+$/i.test(locale) ? locale : `'${locale}'`
      return `  ${key}: { translated: ${c.translated}, total: ${c.total} },`
    })
    .join('\n')
  return `// Generated by scripts/i18n-completeness.ts from the .po catalogs; do not edit.\nexport const completeness: Record<string, { translated: number; total: number }> = {\n${rows}\n}\n`
}

export async function generate(): Promise<string> {
  const { default: config } = await import('../frontend/lingui.config.ts')
  const locales = readdirSync(LOCALES, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort()
  const fallbacks = config.fallbackLocales as Record<string, string | undefined>
  return render(count(locales, fallbacks))
}

if (import.meta.main) {
  writeFileSync(OUT, await generate())
}
