// Package bethesda is the folder loader's extension for Bethesda games: plugin load order (plugins.txt), a LOOT-style
// master sort, script-extender launch, and BSA/BA2 archives kept whole in Data.
package bethesda

import (
	"fmt"
	"path/filepath"
	"strings"

	"github.com/Rethunk-Tech/go-safefs"
	"github.com/Rethunk-Tech/mortar/internal/launchplan"
	"github.com/Rethunk-Tech/mortar/internal/loader"
	"github.com/Rethunk-Tech/mortar/internal/loader/folder"
	"github.com/Rethunk-Tech/mortar/internal/loadorder"
	modpkg "github.com/Rethunk-Tech/mortar/internal/mod"
)

// Role is the catalog path role of the folder holding plugins.txt.
const Role = "plugins"

const (
	CodeMissing = "moduleMissing"
	CodeCycle   = "moduleCycle"
)

var ext = extension{folder.Generated{RoleName: Role, Dir: ".mortar-bethesda", File: "plugins.txt"}}

var _ = folder.Extend(ext)

type extension struct{ folder.Generated }

type spec struct {
	extender string
	starred  bool
}

func specOf(game string) spec {
	switch game {
	case "skyrim-special-edition":
		return spec{extender: "skse64_loader.exe", starred: true}
	case "skyrim":
		return spec{extender: "skse_loader.exe"}
	case "fallout-4":
		return spec{extender: "f4se_loader.exe", starred: true}
	case "fallout-new-vegas":
		return spec{extender: "nvse_loader.exe"}
	case "starfield":
		return spec{extender: "sfse_loader.exe", starred: true}
	default:
		return spec{starred: true}
	}
}

type loaded struct {
	install []plugin
	profile []plugin
	bsa     []string
}

func load(p loader.ProfileView) (loaded, error) {
	var out loaded
	install, err := readPlugins(filepath.Join(p.InstallDir, "Data"))
	if err != nil {
		return loaded{}, err
	}
	out.install = install
	root, err := folder.ProfileModsDir(p.Game, p.Dir)
	if err != nil {
		return loaded{}, err
	}
	own, err := readPlugins(root)
	if err != nil {
		return loaded{}, err
	}
	out.profile = own
	out.bsa, err = listDataArchives(root)
	if err != nil {
		return loaded{}, err
	}
	return out, nil
}

func readPlugins(dir string) ([]plugin, error) {
	entries, found, err := safefs.ReadDirIfExists(dir)
	if err != nil {
		return nil, err
	}
	if !found {
		return nil, nil
	}
	var out []plugin
	for _, e := range entries {
		if e.IsDir() || !isPluginName(e.Name()) {
			continue
		}
		pl, err := parsePlugin(filepath.Join(dir, e.Name()))
		if err != nil {
			continue
		}
		pl.Name = e.Name()
		out = append(out, pl)
	}
	return out, nil
}

func isPluginName(name string) bool {
	switch strings.ToLower(filepath.Ext(name)) {
	case ".esp", ".esm", ".esl":
		return true
	default:
		return false
	}
}

func allPlugins(m loaded) []plugin {
	seen := map[string]bool{}
	var out []plugin
	for _, p := range append(append([]plugin{}, m.install...), m.profile...) {
		key := strings.ToLower(p.Name)
		if seen[key] {
			continue
		}
		seen[key] = true
		out = append(out, p)
	}
	return out
}

func official(m loaded, name string) bool {
	want := strings.ToLower(name)
	for _, p := range m.install {
		if strings.EqualFold(p.Name, want) {
			return true
		}
	}
	return false
}

// Prelaunch writes plugins.txt in LOOT order: install masters, then profile plugins, ESM before ESL before ESP,
// masters before dependents.
func (extension) Prelaunch(p loader.ProfileView) error {
	m, err := load(p)
	if err != nil {
		return err
	}
	ordered, _ := lootOrder(allPlugins(m))
	names := make([]string, len(ordered))
	for i, pl := range ordered {
		names[i] = pl.Name
	}
	return ext.Write(p.Dir, formatPlugins(names, specOf(p.Game).starred))
}

func formatPlugins(names []string, starred bool) []byte {
	var b strings.Builder
	b.WriteString("# This file was generated by Mortar\n")
	for _, n := range names {
		if starred {
			b.WriteByte('*')
		}
		b.WriteString(n)
		b.WriteByte('\n')
	}
	return []byte(b.String())
}

// Contribute places plugins.txt and, when a script extender sits in the install, starts the game through it.
func (e extension) Contribute(plan *launchplan.Plan, p loader.ProfileView) {
	e.Generated.Contribute(plan, p)
	sp := specOf(p.Game)
	if sp.extender == "" || p.InstallDir == "" {
		return
	}
	exe := filepath.Join(p.InstallDir, sp.extender)
	if !safefs.IsFile(exe) {
		return
	}
	_ = plan.OverrideExe(strings.TrimSuffix(strings.ToLower(sp.extender), filepath.Ext(sp.extender)), exe)
	plan.AddProcessName(sp.extender)
}

// Order is the list Prelaunch would write.
func (extension) Order(p loader.ProfileView) ([]loadorder.Row, error) {
	m, err := load(p)
	if err != nil {
		return nil, err
	}
	ordered, findings := lootOrder(allPlugins(m))
	byPlugin := map[string][]loader.Finding{}
	for _, f := range findings {
		byPlugin[strings.ToLower(f.Plugin)] = append(byPlugin[strings.ToLower(f.Plugin)], f)
	}
	rows := make([]loadorder.Row, len(ordered))
	for i, pl := range ordered {
		row := loadorder.Row{
			Position: i + 1, ID: modpkg.NewID(modpkg.FormatFolder, pl.Name), Name: pl.Name,
			Detail: pl.Name, Official: official(m, pl.Name),
		}
		for _, mast := range pl.Masters {
			row.Required = append(row.Required, modpkg.NewID(modpkg.FormatFolder, mast))
		}
		for _, f := range byPlugin[strings.ToLower(pl.Name)] {
			row.Issues = append(row.Issues, loadorder.Issue{Code: f.Code, Message: f.Message, Params: f.Params})
			if f.Kind == "missing-dependency" {
				row.MissingRequired = append(row.MissingRequired, modpkg.NewID(modpkg.FormatFolder, f.Dependency))
			}
			row.Cycle = row.Cycle || f.Code == CodeCycle
		}
		if match := archiveFor(pl.Name, m.bsa); match != "" {
			row.Detail = pl.Name + "+" + match
		}
		rows[i] = row
	}
	return rows, nil
}

func archiveFor(plugin string, archives []string) string {
	stem := strings.TrimSuffix(plugin, filepath.Ext(plugin))
	for _, a := range archives {
		if strings.EqualFold(strings.TrimSuffix(a, filepath.Ext(a)), stem) {
			return a
		}
	}
	return ""
}

// Findings are missing masters and cycles among the profile's plugins.
func (extension) Findings(p loader.ProfileView) []loader.Finding {
	m, err := load(p)
	if err != nil {
		return nil
	}
	_, findings := lootOrder(allPlugins(m))
	own := map[string]bool{}
	for _, pl := range m.profile {
		own[strings.ToLower(pl.Name)] = true
	}
	var out []loader.Finding
	for _, f := range findings {
		if own[strings.ToLower(f.Plugin)] {
			out = append(out, f)
		}
	}
	return out
}

func missingFinding(plugin, master string) loader.Finding {
	return loader.Finding{
		Kind: "missing-dependency", Plugin: plugin, Dependency: master, Code: CodeMissing,
		Message: "requires " + master + ", which is not installed",
		Params:  map[string]string{"other": master},
	}
}

func cycleFinding(names []string) loader.Finding {
	return loader.Finding{
		Kind: "load-exception", Plugin: names[0], Code: CodeCycle,
		Message: "dependency cycle among " + strings.Join(names, ", "),
		Params:  map[string]string{"list": strings.Join(names, ", ")},
	}
}

func listDataArchives(dir string) ([]string, error) {
	entries, found, err := safefs.ReadDirIfExists(dir)
	if err != nil {
		return nil, err
	}
	if !found {
		return nil, nil
	}
	var out []string
	for _, e := range entries {
		if e.IsDir() {
			continue
		}
		switch strings.ToLower(filepath.Ext(e.Name())) {
		case ".bsa", ".ba2":
			if _, err := listArchive(filepath.Join(dir, e.Name())); err != nil {
				return nil, fmt.Errorf("%s: %w", e.Name(), err)
			}
			out = append(out, e.Name())
		}
	}
	return out, nil
}
